"""
ber_vs_difficulty_experiment.py

Runs the three decoders (Fixed threshold, Adaptive threshold, CNN)
at every difficulty level (easy/medium/hard/extreme) and reports
average BER for each. This is the core experiment: it shows whether
the CNN degrades more gracefully than the threshold methods as
scattering/noise increases.

Requires:
  - dataset/<difficulty>/... generated by dataset_generator.py
  - flashlight_cnn_<difficulty>.h5 for each difficulty, trained by
    train_cnn_all_levels.py


"""

import random
import numpy as np
import cv2
from tensorflow.keras.models import load_model

from encoder import text_to_binary
from camera_noise import add_camera_noise_at_level, DIFFICULTY_PRESETS
from threshold_detector import signal_to_binary
from adaptive_threshold import adaptive_signal_to_binary
from ber_calculation import calculate_ber

IMG_SIZE = 64

# =====================================================
# Same circle generation as dataset_generator.py - kept
# identical so frames here match what each CNN trained on
# =====================================================
def generate_on_image():
    img = np.zeros((IMG_SIZE, IMG_SIZE, 3), dtype=np.uint8)
    x = np.random.randint(20, 44)
    y = np.random.randint(20, 44)
    radius = np.random.randint(8, 13)
    brightness = np.random.randint(220, 256)
    cv2.circle(img, (x, y), radius, (brightness,) * 3, -1)
    return img


def generate_off_image():
    return np.zeros((IMG_SIZE, IMG_SIZE, 3), dtype=np.uint8)


def bit_to_frame(bit, difficulty):
    img = generate_on_image() if bit == '1' else generate_off_image()
    return add_camera_noise_at_level(img, difficulty)


def frame_to_signal_value(frame):
    gray = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)
    return int(np.max(gray))


def cnn_decode(frames, model):
    # BGR -> RGB fix, same as cnn_decoder_pipeline.py
    rgb_frames = [cv2.cvtColor(f, cv2.COLOR_BGR2RGB) for f in frames]
    batch = np.array(rgb_frames, dtype="float32") / 255.0
    preds = model.predict(batch, verbose=0)
    return "".join('1' if p[0] > 0.5 else '0' for p in preds)


def run_experiment_at_difficulty(difficulty, num_bits=200, trials=10):
    model = load_model(f"flashlight_cnn_{difficulty}.h5")

    totals = {"Fixed": 0.0, "Adaptive": 0.0, "CNN": 0.0}

    for _ in range(trials):
        binary = "".join(random.choice("01") for _ in range(num_bits))

        frames = [bit_to_frame(b, difficulty) for b in binary]
        signal_values = [frame_to_signal_value(f) for f in frames]

        fixed_bits = signal_to_binary(signal_values)
        adaptive_bits, _ = adaptive_signal_to_binary(signal_values)
        cnn_bits = cnn_decode(frames, model)

        for name, bits in [("Fixed", fixed_bits), ("Adaptive", adaptive_bits), ("CNN", cnn_bits)]:
            _, ber = calculate_ber(binary, bits)
            totals[name] += ber

    return {name: total / trials for name, total in totals.items()}


def run_full_experiment():
    all_results = {}

    for difficulty in DIFFICULTY_PRESETS.keys():
        print(f"\nRunning experiment at difficulty: {difficulty}...")
        results = run_experiment_at_difficulty(difficulty)
        all_results[difficulty] = results
        print(f"  Fixed:    {results['Fixed']:.4f}")
        print(f"  Adaptive: {results['Adaptive']:.4f}")
        print(f"  CNN:      {results['CNN']:.4f}")

    print(f"\n{'='*55}")
    print("SUMMARY - average BER by difficulty and method")
    print(f"{'='*55}")
    print(f"{'difficulty':<12}{'Fixed':<10}{'Adaptive':<10}{'CNN':<10}")
    for difficulty, results in all_results.items():
        print(f"{difficulty:<12}{results['Fixed']:<10.4f}{results['Adaptive']:<10.4f}{results['CNN']:<10.4f}")

    return all_results


if __name__ == "__main__":
    run_full_experiment()